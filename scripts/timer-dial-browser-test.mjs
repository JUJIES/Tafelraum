#!/usr/bin/env node
// Isolated real CanvasSurface + Room. Start live-canvas-browser-check.mjs --clips.
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.argv[2]).href);
const origin=`http://127.0.0.1:${Number(process.env.LIVE_CANVAS_HOST_PORT??5179)}`;
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE??'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:1280,height:900},hasTouch:true});
const page=await context.newPage();page.setDefaultTimeout(10000);const errors=[],checks=[];const record=message=>{checks.push(message);console.log(message)};
page.on('pageerror',e=>{errors.push(e.message);console.error(e.message)});
const getDuration=()=>page.evaluate(()=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget')?.customData.timerDurationSeconds);
const waitDuration=value=>page.waitForFunction(value=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget')?.customData.timerDurationSeconds===value,value);
const dialPoint=async(fraction,scope=page)=>scope.locator('.timer-widget__dial').evaluate((el,f)=>{
  const r=el.getBoundingClientRect(),a=(-225+270*f)*Math.PI/180;
  const matrix=new DOMMatrixReadOnly(getComputedStyle(el.parentElement).transform);
  const dx=96*Math.cos(a),dy=96*Math.sin(a);
  return {x:r.left+r.width/2+matrix.a*dx+matrix.c*dy,y:r.top+r.height/2+matrix.b*dx+matrix.d*dy};
},fraction);
const touch=async(type,p)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type==='touchEnd'||type==='touchCancel'?[]:[{x:p.x,y:p.y,radiusX:8,radiusY:8,force:1,id:1}]});
const cdp=await context.newCDPSession(page);
try {
  await page.goto(`${origin}/src/live/clip.browser.html?lesson=synthetic-timer-dial-${Date.now()}&theme=dark`);
  await page.waitForFunction(()=>window.clipFixture?.port&&window.clipFixture?.api);
  await page.waitForTimeout(500);
  await page.evaluate(()=>window.clipFixture.port.placeTimer({clientX:550,clientY:430}));
  await page.locator('.timer-widget').waitFor();
  const geometry=()=>page.evaluate(()=>{const e=window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget');return {x:e.x,y:e.y,duration:e.customData.timerDurationSeconds}});
  await page.evaluate(()=>window.clipFixture.api.setActiveTool({type:'selection'}));
  assert.equal(await page.locator('.timer-widget__grip').count(),0);
  const initial=await geometry(), box=await page.locator('.timer-widget').boundingBox();
  await touch('touchStart',{x:box.x+10,y:box.y+10});await touch('touchMove',{x:box.x+90,y:box.y+65});await touch('touchEnd',{});
  await page.waitForFunction(x=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget').x>x,initial.x);
  const moved=await geometry();assert.equal(moved.duration,initial.duration);
  await page.locator('.timer-widget__move-edge.at-n.is-before').waitFor();
  const edge=await page.locator('.timer-widget__move-edge.at-n.is-before').boundingBox();
  await touch('touchStart',{x:edge.x+edge.width/2,y:edge.y+edge.height/2});await touch('touchMove',{x:edge.x+edge.width/2+35,y:edge.y+edge.height/2+25});await touch('touchEnd',{});
  await page.waitForFunction(x=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget').x>x,moved.x);
  assert.equal((await geometry()).duration,initial.duration);
  record('Touch moves the timer from free space and the selected frame without changing its duration');
  await page.evaluate(()=>window.clipFixture.api.updateScene({appState:{zoom:{value:.5}}}));
  await page.waitForTimeout(100);
  const smallEdge=await page.locator('.timer-widget__move-edge.at-e.is-before').boundingBox();
  assert.ok(smallEdge.width>=40&&smallEdge.height>10,'selected frame retains a practical touch target at 50% zoom');
  const beforeSmall=await geometry();
  await touch('touchStart',{x:smallEdge.x+smallEdge.width/2,y:smallEdge.y+smallEdge.height/2});await touch('touchMove',{x:smallEdge.x+smallEdge.width/2+25,y:smallEdge.y+smallEdge.height/2+15});await touch('touchEnd',{});
  await page.waitForFunction(x=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget').x>x,beforeSmall.x);
  await page.evaluate(()=>window.clipFixture.api.updateScene({appState:{zoom:{value:1}}}));
  record('Selected frame remains touch-draggable at 50% canvas zoom');
  await page.getByRole('button',{name:'30 Sekunden',exact:true}).tap();await waitDuration(30);
  await page.getByRole('button',{name:'5 Minuten',exact:true}).tap();await waitDuration(300);
  record('Touch taps select exact labels');
  const before=await getDuration(),a=await dialPoint(.6),b=await dialPoint(.7);
  await touch('touchStart',a);await touch('touchMove',b);
  assert.equal(await getDuration(),before,'drag preview must not persist');
  assert.equal(await page.locator('.timer-widget__time span').textContent(),'10:00');
  await touch('touchEnd',b);await waitDuration(600);
  record('Touch drag previews without writes and commits on release');
  await page.evaluate(()=>window.clipFixture.port.undo());await waitDuration(300);
  await page.evaluate(()=>window.clipFixture.port.redo());await waitDuration(600);
  record('One Undo/Redo covers the entire gesture');
  const c=await dialPoint(.3);await touch('touchStart',b);await touch('touchMove',c);await touch('touchCancel',c);
  assert.equal(await getDuration(),600);
  record('Cancelled touch never changes duration');
  await touch('touchStart',b);await touch('touchMove',c);
  await page.getByRole('button',{name:'Ton einschalten',exact:true}).evaluate(el=>el.click());
  // Disabled controls ignore unrelated actions during a held draft.
  assert.equal(await page.getByRole('button',{name:'Ton einschalten',exact:true}).isDisabled(),true);
  await touch('touchCancel',c);
  await page.getByRole('button',{name:'Dauer einstellen',exact:true}).click();
  await page.getByRole('textbox',{name:'Dauer in Minuten:Sekunden'}).fill('1440:00');await page.getByRole('button',{name:'Übernehmen',exact:true}).click();await waitDuration(86400);
  await page.getByRole('button',{name:'Dauer einstellen',exact:true}).click();await page.getByRole('textbox').fill('0:01');await page.getByRole('button',{name:'Übernehmen',exact:true}).click();await waitDuration(1);
  record('Precise entry retains 1 second and 24 hours');
  await page.getByRole('button',{name:'2 Minuten',exact:true}).click();await waitDuration(120);
  await page.locator('.timer-widget__start').click();await page.waitForTimeout(1100);
  assert.equal(await page.locator('.timer-widget__stop').count(),0,'running countdown hides selection scale');
  const runningBefore=await geometry(), runningBox=await page.locator('.timer-widget').boundingBox();
  await touch('touchStart',{x:runningBox.x+10,y:runningBox.y+10});await touch('touchMove',{x:runningBox.x+35,y:runningBox.y+30});await touch('touchEnd',{});
  await page.waitForFunction(x=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget').x>x,runningBefore.x);
  assert.equal(await page.locator('.timer-widget__start').textContent(),'Pause');
  await page.locator('.timer-widget__start').click();assert.equal(await page.locator('.timer-widget__start').textContent(),'Weiter');
  await page.getByRole('button',{name:'Zurücksetzen',exact:true}).click();
  record('Start/pause/reset preserve runtime semantics');
  await page.getByRole('button',{name:'5 Minuten',exact:true}).press('Enter');await waitDuration(300);
  await page.getByRole('button',{name:'10 Sekunden',exact:true}).tap();await waitDuration(10);
  const gapStart=await dialPoint(0);await touch('touchStart',gapStart);
  for(const fraction of [-.05,-.15,-.25,-.35])await touch('touchMove',await dialPoint(fraction));
  assert.equal(await page.locator('.timer-widget__time span').textContent(),'0:10','crossing the bottom gap cannot wrap to one hour');
  await touch('touchEnd',gapStart);assert.equal(await getDuration(),10);
  record('Keyboard selection and touch across the open gap work without wrapping');

  const popup=context.waitForEvent('page');await page.evaluate(()=>window.clipFixture.room.start());const room=await popup;
  room.on('pageerror',e=>errors.push(e.message));await room.waitForLoadState();await room.locator('.timer-widget').waitFor();
  await room.getByRole('button',{name:'3 Minuten',exact:true}).tap();await waitDuration(180);
  await page.waitForFunction(()=>document.querySelector('.timer-widget__time span')?.textContent==='3:00');
  record('Room touch selection updates the canonical teacher timer');
  await page.waitForTimeout(500); // Let the confirmed Room projection catch up with the latest duration revision.
  const roomBefore=await geometry(), roomBox=await room.locator('.timer-widget').boundingBox();
  await room.mouse.move(roomBox.x+10,roomBox.y+10);await room.mouse.down();await room.mouse.move(roomBox.x+55,roomBox.y+45,{steps:5});await room.mouse.up();
  await page.waitForFunction(x=>window.clipFixture.api.getSceneElements().find(e=>e.customData?.surfaceKind==='timer-widget').x>x,roomBefore.x);
  assert.equal((await geometry()).duration,180);
  record('Room moves the shared timer from free space without changing its time');
  const d=await dialPoint(.4);await touch('touchStart',d);await touch('touchMove',c);
  await room.getByRole('button',{name:'4 Minuten',exact:true}).tap();await waitDuration(240);
  await touch('touchEnd',c);assert.equal(await getDuration(),240,'stale teacher draft cannot replace a newer Room revision');
  record('Competing Room revision cancels a held teacher draft');
  await room.close();
  await page.evaluate(()=>{const api=window.clipFixture.api;api.updateScene({elements:api.getSceneElements().map(e=>({...e,angle:Math.PI/4,version:e.version+1,versionNonce:1001})),appState:{zoom:{value:1.3},selectedElementIds:{}}});});
  await page.getByRole('button',{name:'2 Minuten',exact:true}).tap();await waitDuration(120);
  const r0=await dialPoint(.3),r1=await dialPoint(.4);
  const camera=await page.evaluate(()=>{const s=window.clipFixture.api.getAppState();return [s.scrollX,s.scrollY]});
  await touch('touchStart',r0);await touch('touchMove',r1);await touch('touchEnd',r1);await waitDuration(180);
  assert.deepEqual(await page.evaluate(()=>{const s=window.clipFixture.api.getAppState();return [s.scrollX,s.scrollY]}),camera);
  record('Rotated/zoomed touch drag keeps exact time and leaves canvas camera unchanged');
  await page.evaluate(()=>{const api=window.clipFixture.api;api.updateScene({elements:api.getSceneElements().map(e=>({...e,angle:0,version:e.version+1,versionNonce:1002})),appState:{zoom:{value:1}}});});
  await page.getByRole('button',{name:'4 Minuten',exact:true}).tap();await waitDuration(240);
  await page.evaluate(()=>window.clipFixture.port.flushPersistence());await page.reload();await page.locator('.timer-widget').waitFor();await waitDuration(240);
  record('Saved config reloads without a running clock');
  await mkdir('output/timer-dial',{recursive:true});await page.screenshot({path:'output/timer-dial/teacher-dark.png'});await page.locator('.timer-widget').screenshot({path:'output/timer-dial/timer-dark.png'});
  await page.getByRole('button',{name:'Theme wechseln',exact:true}).click();await page.screenshot({path:'output/timer-dial/teacher-light.png'});await page.locator('.timer-widget').screenshot({path:'output/timer-dial/timer-light.png'});
  assert.deepEqual(errors,[]);await writeFile('output/timer-dial/browser-checks.json',JSON.stringify({checks,errors},null,2)+'\n');
} catch(error) {console.error(await page.evaluate(()=>({elements:window.clipFixture?.api?.getSceneElements().map(e=>({id:e.id,data:e.customData})),widgets:document.querySelectorAll('.timer-widget').length,text:document.body.innerText.slice(-1200)})));throw error;} finally {await browser.close();}
